/** Translate authored presentation fields while preserving links, icons and technology names. */
export function getPortfolioCopy(locale: "en" | "km") {
  const text = (value: string) => Object.hasOwn(COPY_KEYS, value) ? translateMessage(locale, COPY_KEYS[value]!) : value;
  return {
    profile: { ...portfolioProfile, title: text(portfolioProfile.title), tagline: text(portfolioProfile.tagline) },
    metrics: portfolioMetrics.map(item => ({ ...item, value: text(item.value), label: text(item.label) })),
    about: portfolioAbout.map(text), highlights: portfolioHighlights.map(text),
    skills: portfolioSkills.map(item => ({ ...item, title: text(item.title), description: text(item.description), skills: item.skills.map(text) })),
    projects: portfolioProjects.map(item => ({ ...item, title: text(item.title), description: text(item.description), tags: item.tags.map(text) })),
    workingStyle: portfolioWorkingStyle.map(item => ({ ...item, title: text(item.title), description: text(item.description) })),
    contacts: portfolioContacts.map(item => ({ ...item, label: text(item.label) })),
  };
}
