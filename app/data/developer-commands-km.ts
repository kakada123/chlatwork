export function localizeCommandCategory(category: string, locale: "en" | "km"): string {
  return Object.hasOwn(CATEGORY_KEYS, category) ? translateMessage(locale, CATEGORY_KEYS[category]) : category;
}

export function localizeDeveloperCommand(item: DeveloperCommand, locale: "en" | "km"): DeveloperCommand {
  const prefix = `developerCommands.entries.${item.id}`;
  return {
    ...item,
    title: translateMessage(locale, `${prefix}.title`),
    description: translateMessage(locale, `${prefix}.description`),
    ...(item.consequence ? { consequence: translateMessage(locale, `${prefix}.consequence`) } : {}),
    ...(item.variables ? { variables: item.variables.map((variable) => ({
      ...variable,
      label: Object.hasOwn(VARIABLE_KEYS, variable.label) ? translateMessage(locale, VARIABLE_KEYS[variable.label]) : variable.label,
    })) } : {}),
  };
}
