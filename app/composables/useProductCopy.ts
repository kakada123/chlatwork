export function useProductCopy(locale?: { readonly value: boolean }) {
  const { t } = useAppI18n(locale);
  const productText = (label: string): string =>
    Object.hasOwn(PRODUCT_MESSAGE_KEYS, label) ? t(PRODUCT_MESSAGE_KEYS[label]!) : label;
  // A label alone cannot prove it is a preset rather than authored text.
  const productCategoryText = (label: string, categoryKey?: string): string =>
    categoryKey && categoryKey === label ? productText(categoryKey) : label;
  return { productText, productCategoryText };
}
